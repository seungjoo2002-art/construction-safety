# 엑셀 재해종류 -> 예측모델 유형 (재해종류_MAP 을 뒤집은 것)
_역_재해 = {v: k for k, vs in 재해종류_MAP.items() for v in vs}

_번호 = re.compile(r"^\s*\d+(?:\.\d+)*\.?\s*")


def 번호제거(s: str) -> str:
    """'1. 토공사' -> '토공사',  '1.1.1 굴착 장비반입' -> '굴착 장비반입'"""
    return _번호.sub("", str(s)).strip()


def 대책분리(s: str) -> list[str]:
    """'▶ A ▶ B ▶ C' -> ['A', 'B', 'C']"""
    return [t.strip() for t in re.split(r"[▶\n]+", str(s)) if t.strip()]


def 엑셀읽기():
    import pandas as pd

    src = glob.glob(str(BASE / "*고위험요인(SIF)*.xlsx"))
    if not src:
        raise FileNotFoundError("SIF 아카이브 xlsx 파일을 찾을 수 없습니다")
    # 헤더가 2줄로 병합돼 있어 1~2행을 헤더로 읽은 뒤 이름을 직접 지정한다
    df = pd.read_excel(src[0], sheet_name="아카이브(건설업)", header=[1, 2])
    df.columns = ["_", "연번", "공종", "작업명", "단위작업명", "재해종류",
                  "재해개요", "기인물", "재해유발요인", "감소대책"]
    return df[df["연번"].notna()].copy()


def main() -> None:
    df = 엑셀읽기()

    records, 무매핑 = [], 0
    for i, r in enumerate(df.itertuples(index=False), start=1):
        공종 = 번호제거(r.공종)
        작업명 = 번호제거(r.작업명)
        단위작업 = 번호제거(r.단위작업명)
        재해종류 = str(r.재해종류).strip()
        기인물 = str(r.기인물).strip()
        유발요인 = str(r.재해유발요인).strip()

        예측유형 = _역_재해.get(재해종류)
        if 예측유형 is None:
            무매핑 += 1

        records.append({
            "id": i,
            "공종": 공종,
            "작업명": 작업명,
            "단위작업명": 단위작업,
            "재해종류": 재해종류,
            "예측유형": 예측유형,          # 예측모델 5종 (없으면 None)
            "기인물": 기인물,
            "유발요인": 유발요인,
            "재해개요": str(r.재해개요).strip(),
            "대책": 대책분리(r.감소대책),
            # bge-m3 로 벡터화할 문장. 재해개요는 날짜·장소 노이즈가 많아 제외한다.
            "검색문장": f"{공종} {작업명} {단위작업} 중 {기인물}(으)로 인한 {재해종류} — {유발요인}",
        })

    with open(OUT, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    대책수 = sum(len(r["대책"]) for r in records)
    print(f"저장: {OUT.name}  {len(records):,}건")
    print(f"  예측유형 매핑됨   {len(records) - 무매핑:,}건 ({(len(records)-무매핑)/len(records)*100:.1f}%)")
    print(f"  예측유형 없음     {무매핑:,}건  (감전·익사·화상 등, 공종/작업명으로는 검색됨)")
    print(f"  분리된 대책 총합  {대책수:,}개  (평균 {대책수/len(records):.1f}개/건)")
    print(f"  공종 {df['공종'].nunique()}종 / 작업명 {df['작업명'].nunique()}종 / 재해종류 {df['재해종류'].nunique()}종")


if __name__ == "__main__":
    main()
